<script>
    document.addEventListener('DOMContentLoaded', function() {
    // Edit User Modal
    document.querySelectorAll('.edit-user').forEach(button => {
        button.addEventListener('click', function() {
            const user = JSON.parse(this.dataset.user);
            const role = this.dataset.role;

            const form = document.getElementById('editUserForm');
            form.action = `/admin/users/${user.id}`;

            form.querySelector('input[name="name"]').value = user.name;
            form.querySelector('input[name="email"]').value = user.email;
            form.querySelector('input[name="phone"]').value = user.phone || '';
            form.querySelector('select[name="role"]').value = role;
            form.querySelector('select[name="department_id"]').value = user.department_id;
            form.querySelector('select[name="branch_id"]').value = user.branch_id;

            new bootstrap.Modal(document.getElementById('editUserModal')).show();
        });
    });
});
</script>
